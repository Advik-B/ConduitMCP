// Which engine classes and members each dedicated Conduit tool actually fronts.
//
// This table is the only hand-written input to the audit, and it is what makes a
// T0 claim auditable: every member listed here was read off the handler that
// calls it (bridge/src/handlers/**), not inferred from a tool's name. Adding a
// tool without extending this table is allowed - the tool simply contributes no
// T0 coverage until someone says which engine API it fronts - but a rule naming
// a tool that no longer exists fails the harness test.

export interface CoverageRule {
  /** Tool name as registered by the broker. */
  tool: string;
  /** Ops of that tool the rule covers, for the report's justification column. */
  ops?: string[];
  /** Engine classes the rule applies to. Subclasses inherit the coverage. */
  classes: string[];
  /** Member names covered. */
  members: string[];
  /** Which bridge the coverage exists on. */
  side: "runtime" | "editor" | "both";
  note?: string;
}

